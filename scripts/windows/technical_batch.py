"""Freeze and persist only 27 native Windows technical fits plus 24 probes.

This is an explicitly bounded engineering gate, never the 41,472 formal grid.
Protocol generation and sampling are separate commands and commits. No inputs
are generated by run/resume, and cache selection does not inspect main results.
"""
