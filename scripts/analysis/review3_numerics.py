#!/usr/bin/env python3
"""Rebuild third-review numerical explanations from pinned saved evidence only."""
import argparse
import csv
from decimal import Decimal, localcontext, ROUND_FLOOR, ROUND_CEILING
from fractions import Fraction as F
import hashlib
import json
import math
from pathlib import Path


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def exact(record, endpoint):
    return F(*map(int, record[endpoint]))


def ball(value):
    mid, rad = [F(int(n)) * F(2)**int(e) for n, e in value]
    assert rad >= 0
    return mid-rad, mid+rad


def sci_bound(x, upper, digits=7):
    # Decimal directed rounding from exact rational endpoints, never via float.
    with localcontext() as ctx:
        ctx.prec = 70
        ctx.rounding = ROUND_CEILING if upper else ROUND_FLOOR
        d = Decimal(x.numerator)/Decimal(x.denominator)
        exponent = d.adjusted()
        quantum = Decimal(1).scaleb(exponent-digits+1)
        d = d.quantize(quantum)
        mantissa = d.scaleb(-exponent)
        result = F(str(mantissa))*F(10)**exponent
        assert result >= x if upper else result <= x
        return rf"{mantissa}\times10^{{{exponent}}}"


def render(root, inputs):
    root, inputs = Path(root), Path(inputs)
    m = json.loads((inputs/'MANIFEST.json').read_bytes())
    sources = {}
    for name, digest in m['files'].items():
        assert sha(inputs/name) == digest, name
        sources['inputs/'+name] = digest
    l2p = root/'benchmark/analysis/outputs/l2-rare-reference-is-v1/SUMMARY.json'
    assert sha(l2p) == '054160b69f3182c5c369726f5746088c4476c167dedad837c4c4c5bdd15d813b'
    w1p = root/'benchmark/analysis/outputs/w1-reference-enclosure-v1/audit/audit.json'
    assert sha(w1p) == '228481183a493d902747a76e2d0127b1b664e99df74cfccfad18d9e89c8a011c'
    l2, w1 = json.loads(l2p.read_bytes()), json.loads(w1p.read_bytes())
    assert w1['passed'] and w1['new_integrand_evaluations'] == w1['new_mcmc_calls'] == 0
    sources[str(l2p.relative_to(root))] = sha(l2p)
    sources[str(w1p.relative_to(root))] = sha(w1p)
    counts = {}
    for model in ['L2','W1']:
        rows = list(csv.DictReader((inputs/f'{model}-tasks.csv').read_text().splitlines()))
        rows = [r for r in rows if r['phase'] == 'main']
        assert len(rows) == 18 and sum(int(r['planned']) for r in rows) == 432
        by_budget = {n:sum(json.loads(r['outcomes']).get('valid',0) for r in rows if int(r['budget']) == n) for n in [1024,4096]}
        counts[model] = {'valid_by_budget':by_budget, 'valid_fits':sum(by_budget.values()), 'retained_state_entries':sum(4*n*v for n,v in by_budget.items()), 'planned_fits':432}
    assert counts['L2']['valid_fits'] == 414 and counts['W1']['valid_fits'] == 432
    refs = [('L2 Q1', 'L2', l2['reference_estimates'][0]['probability']), ('L2 Q2','L2',l2['reference_estimates'][1]['probability'])]
    wlo, whi = exact(w1['combined']['beta_positive'],'lower_exact'), exact(w1['combined']['beta_positive'],'upper_exact')
    refs.append(('W1','W1',float((wlo+whi)/2)))
    rare = []
    for label, model, p in refs:
        n = counts[model]['retained_state_entries']
        rare.append({'reference':label, 'model':model, 'p':p, 'state_entries':n,'expected_iid_hits':n*p,'iid_zero_probability':math.exp(n*math.log1p(-p)), 'iid_relative_standard_error':math.sqrt((1-p)/(n*p)), 'hypothetical_iid_only':True})
    difference = abs(l2['reference_estimates'][1]['probability']-l2['reference_estimates'][0]['probability'])
    ratio = difference / math.hypot(*(e['mcse'] for e in l2['reference_estimates']))
    tail = json.loads((inputs/'w1-tail.json').read_bytes())
    decay = ball(tail['minimum_decay'])[0]
    mass = ball(tail['upper_bounds'][0])[1]
    assert decay > 0 and mass == exact(w1['tails'][0],'upper_exact')
    intermediates=[]
    for method in w1['methods']:
        errors = [sum(exact(region[j],'upper_exact') for region in method['quadrature_remainders']) for j in range(7)]
        zlo=exact(method['denominator'],'lower_exact')
        assert zlo > 0 and all(e>=0 for e in errors)
        intermediates.append({'method':method['method'],'normalizer_lower_exact':str(zlo),'tail_mass_upper_exact':str(mass),'min_decay_lower_exact':str(decay),'density_remainder_upper_exact':str(errors[0]),'continuous_numerator_remainder_upper_exact':[str(e) for e in errors[1:]],'tail_posterior_mass_upper_exact':str(mass/zlo)})
    macros = '% Generated by review3_numerics.py; saved evidence only.\n'
    for label, model in [('LTwo','L2'),('WOne','W1')]:
        rr=next(r for r in rare if r['model']==model)
        macros += rf"\newcommand{{\PBIID{label}States}}{{{rr['state_entries']}}}"+'\n'
        macros += rf"\newcommand{{\PBIID{label}Hits}}{{{rr['expected_iid_hits']:.6g}}}"+'\n'
        macros += rf"\newcommand{{\PBIID{label}Zero}}{{{100*rr['iid_zero_probability']:.3f}}}"+'\n'
    rows=[]
    for r in rare:
        mantissa, exponent = f"{r['p']:.5e}".split('e')
        probability = rf"{mantissa}\times10^{{{int(exponent)}}}"
        rows.append(f"{r['reference']} & {r['state_entries']} & ${probability}$ & {r['expected_iid_hits']:.6g} & {100*r['iid_zero_probability']:.3f}\\%"+r'\\')
    raretex = r'''\subsection{稀有事件的理想独立抽样基准}
\label{sec:rare-iid}
这里以正式任务表中的保留状态条目数说明预算量级，不改变原独立重复单位。L2在1024/4096预算分别有216/198份有效四链拟合，W1各有216份。设事件概率为$p$，假想$N$个状态均为独立后验样本，则命中数的期望为$Np$，零命中概率为$(1-p)^N$。表\ref{tab:rare-iid}使用两套L2重要性点估计及W1区间中点；L2参考有近似MCSE，W1中点只用于量级展示。
\begin{table}[htbp]\centering\small
\begin{tabular}{lrrrr}\toprule
参考 & 保留状态条目数 & $p$ & $Np$ & $(1-p)^N$\\\midrule
'''+'\n'.join(rows)+r'''
\bottomrule\end{tabular}
\caption{全零事件的理想IID参照。实际MCMC相关，同核执行、设备和预算间还共享部分轨迹；这些条目不是独立信息数，表中概率不作为实际运行的零命中概率。}
\label{tab:rare-iid}\end{table}
\FloatBarrier
独立假设下，经验频率的相对标准误为$\sqrt{(1-p)/(Np)}$；当前即使使用表中的总条目数，仍远大于1。更一般地，只要每个状态的边缘分布正确，线性期望和并集界给出$\E[K]=Np$和$\Pr(K\geq1)\leq Np$，无需独立性；未平稳的实际初值不自动满足这一前提。全零结果本身因此不足以诊断混合不良，它揭示的是普通经验频率在当前预算下无法提供有用的稀有事件相对精度。常量事件的$\hat R$/ESS仍未定，与其他函数的探索诊断分开解释。
'''
    boundrows=[]
    metrics=[(r'$Z_g$下界','normalizer_lower_exact',False), (r'$B_0$上界','tail_mass_upper_exact',True),(r'$\min_k\kappa_k$下界','min_decay_lower_exact',False), (r'密度累计余项上界','density_remainder_upper_exact',True),(r'连续函数分子最大余项上界',None,True),(r'$B_0/Z_g$上界','tail_posterior_mass_upper_exact',True)]
    for name,key,upper in metrics:
        vals=[F(m[key]) if key else max(map(F,m['continuous_numerator_remainder_upper_exact'])) for m in intermediates]
        boundrows.append(name+' & '+ ' & '.join('$'+sci_bound(v,upper)+'$' for v in vals)+r'\\')
    boundtex=r'''\begin{table}[htbp]\centering\small
\begin{tabular}{lrr}\toprule
关键中间界 & 两点Gauss--Legendre & Simpson\\\midrule
'''+'\n'.join(boundrows)+r'''
\bottomrule\end{tabular}
\caption{W1的数值包络中间量，均从保存的精确有理端点向外舍入。$Z_g=\int g(z)\,dz$包含固定Jacobian和$-\ell(c)$平移，是前节所定义的缩放归一化常数；$B_0$与求积余项使用同一尺度。密度及六个连续函数分子的累计余项覆盖两个矩形；事件只使用正侧密度余项。共同扇区尾界适用于两规则。最后一行仅为归一化尾部质量界，不能替代无界矩函数的尾部误差界。}
\label{tab:w1-intermediates}\end{table}
'''
    result={'identity':'manuscript-review-v3-derived-interpretation-v1','inputs':sources,'counts':counts,'rare_iid':rare,'importance_comparison':{'relative_difference_to_q1':difference/l2['reference_estimates'][0]['probability'],'difference_over_combined_approx_mcse':ratio},'w1_intermediates':intermediates,'new_mcmc_fits':0,'new_integrand_evaluations':0,'frozen_protocols_changed':0,'scope':'Post hoc interpretation and saved-bound reporting; not a new scientific experiment or independent software correctness proof.'}
    outputs={'review3-scalars.generated.tex':macros,'review3-rare-iid.generated.tex':raretex,'w1-intermediates.generated.tex':boundtex,'review3-numerics.json':json.dumps(result,ensure_ascii=False,indent=2)+'\n'}
    return outputs


def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--root',type=Path,required=True);p.add_argument('--inputs',type=Path,required=True);p.add_argument('--output',type=Path,required=True);args=p.parse_args()
    values=render(args.root,args.inputs);args.output.mkdir(parents=True,exist_ok=False)
    for name,value in values.items():(args.output/name).write_text(value,encoding='utf8')
    print(json.dumps({'outputs':list(values),'new_mcmc_fits':0}))


if __name__=='__main__':main()
