#!/usr/bin/env python3
"""Render S2 prose/tables from independently reviewed, pinned evidence."""
import argparse
import csv
import hashlib
import json
from pathlib import Path
import re


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def render(root, templates, output):
    if output.exists():
        raise FileExistsError('Use a new output directory')
    manifest=json.loads((root/'files.sha256.json').read_text())
    for name,digest in manifest.items():
        if Path(name).is_absolute() or '..' in Path(name).parts or sha(root/name)!=digest:
            raise ValueError('Evidence identity differs: '+name)
    summary=json.loads((root/'review/SUMMARY.json').read_text())
    if not summary['passed'] or not summary['actual_qualification_passed'] or not summary['confirmation_selection_recomputed']:
        raise ValueError('Actual independent review incomplete')
    rows=list(csv.DictReader((root/'rebuilt/calls.csv').open(newline='')))
    by_id={r['id']:r for r in rows}
    if len(rows)!=53 or summary['registered_four_chain_calls']!=44:
        raise ValueError('Finite-study denominator differs')
    matrix=[]
    for model in ['G1','G2','A1','L1','L2','H1','H2','M1','W1']:
        selected=[by_id[f'main-{model}-w{w}-d{int(d)}'] for w,d in [(1,True),(4,True),(1,False),(4,False)]]
        original='有效' if selected[0]['original_outcome']=='valid' else '未分类失败'
        states=['完成' if r['status']=='completed' else '资源停止' for r in selected]
        matrix.append(model+' & '+original+' & '+' & '.join(states)+r'\\')
    failed=json.loads((root/'review/failed-call-review.json').read_text())
    resources=[]
    labels={'diagnostic-G2-legacy-w4':'旧G2，ESS重放',
            'main-G2-w4-d1':'G2，主体诊断开启','main-A1-w4-d1':'A1，主体诊断开启',
            'confirmation-G2-w4-d1':'G2，确认诊断开启','confirmation-A1-w4-d1':'A1，确认诊断开启'}
    for row in failed:
        r=row['resources']
        resources.append(labels[row['id']]+f" & {r['max_sampled_tree_rss_bytes']/1024**3:.2f} & {r['kernel_peak_job_commit_bytes']/1024**3:.2f} & {len(r['memory_limit_messages'])}"+r'\\')
    modern=json.loads((root/'review/modern-R-comparison.json').read_text())
    tokens={'MATRIX':'\n'.join(matrix),'RESOURCES':'\n'.join(resources),
            'R_NUMERIC_DIFFERENCES':str(sum(len(r['numeric_differences']) for r in modern)),
            'R_MAX_SCALED_DIFFERENCE':f"{max(r['max_scaled_difference'] for r in modern):.2e}".replace('e-15',r'\times10^{-15}')}
    output.mkdir(parents=True)
    provenance={'identity':'nuts-localization-paper-fragments-v1','evidence_manifest_sha256':sha(root/'files.sha256.json'),
                'generator_sha256':sha(Path(__file__)),'inputs':manifest,'templates':{},'outputs':{},'new_sampler_calls':0}
    for part in ['main','si']:
        p=templates/f'nuts-localization-{part}.template.tex';text=p.read_text()
        required=set(re.findall('@([A-Z0-9_]+)@',text))
        if required-set(tokens):raise ValueError('Undefined template token')
        rendered='% Generated by write_nuts_localization_tex.py; edit the template.\n'+re.sub('@([A-Z0-9_]+)@',lambda m:tokens[m.group(1)],text)
        dst=output/f'nuts-localization-{part}.generated.tex';dst.write_text(rendered)
        provenance['templates'][p.name]=sha(p);provenance['outputs'][dst.name]=sha(dst)
    (output/'nuts-localization.provenance.json').write_text(json.dumps(provenance,ensure_ascii=False,indent=2)+'\n')
    print(json.dumps({'generated':list(provenance['outputs']),'new_sampler_calls':0}))


if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--root',required=True,type=Path);p.add_argument('--templates',required=True,type=Path)
    p.add_argument('--output',required=True,type=Path);a=p.parse_args();render(a.root,a.templates,a.output)
